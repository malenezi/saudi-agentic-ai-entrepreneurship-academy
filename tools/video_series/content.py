def hook(lines, kicker=""):
    """lines: list of (cue, text, cls)"""
    h = f'<div class="kicker" data-at="0">{kicker}</div>' if kicker else ""
    h += "".join(f'<div class="hl {c}" data-at="{a}">{t}</div>' for a, t, c in lines)
    return f'<div class="sc hook">{h}</div>'


def cards(title, items, cols=None, sub="", cls=""):
    """items: list of (cue, text[, small])"""
    cols = cols or len(items)
    body = ""
    for i, it in enumerate(items, 1):
        small = f'<div class="csm">{it[2]}</div>' if len(it) > 2 else ""
        body += f'<div class="card" data-at="{it[0]}"><div class="cn">{i:02d}</div><div class="ct">{it[1]}</div>{small}</div>'
    s = f'<div class="sub" data-at="{sub[0]}">{sub[1]}</div>' if sub else ""
    return (f'<div class="sc list {cls}"><div class="ttl" data-at="0">{title}</div>'
            f'<div class="grid" style="--cols:{cols}">{body}</div>{s}</div>')


def flow(title, nodes, sub="", lead=""):
    """nodes: list of (cue, text, kind) kind in '', 'human', 'in'"""
    body = ""
    for i, (a, t, k) in enumerate(nodes):
        if i:
            body += f'<div class="arr" data-at="{a}"><svg viewBox="0 0 60 24"><path d="M58 12H6M16 3L5 12l11 9" fill="none" stroke="currentColor" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"/></svg></div>'
        body += f'<div class="node {k}" data-at="{a}" data-pulse="{a}"><div class="nt">{t}</div></div>'
    l = f'<div class="lead" data-at="{lead[0]}">{lead[1]}</div>' if lead else ""
    s = f'<div class="sub" data-at="{sub[0]}">{sub[1]}</div>' if sub else ""
    return f'<div class="sc flow"><div class="ttl" data-at="0">{title}</div>{l}<div class="pipe">{body}</div>{s}</div>'


def quote(parts, cap="", intro=""):
    """parts: list of (cue, text, cls)"""
    body = "".join(f'<span class="qp {c}" data-at="{a}">{t} </span>' for a, t, c in parts)
    i = f'<div class="kicker" data-at="0">{intro}</div>' if intro else ""
    c = f'<div class="qcap" data-at="{cap[0]}">{cap[1]}</div>' if cap else ""
    return f'<div class="sc quote">{i}<div class="qm" data-at="{parts[0][0]}">”</div><div class="qt">{body}</div>{c}</div>'


def endcard(lines, strip=""):
    body = "".join(f'<div class="el {c}" data-at="{a}">{t}</div>' for a, t, c in lines)
    s = f'<div class="estrip" data-at="{strip[0]}">{strip[1]}</div>' if strip else ""
    return (f'<div class="sc end light"><img class="elogo" src="logo.png" data-at="0" data-fx="pop">'
            f'<div class="ename" data-at="0.25">{ACADEMY}</div>'
            f'<div class="een" data-at="0.45">Saudi Agentic AI Entrepreneurship Academy <b>(SAAEA)</b></div>'
            f'{s}{body}<div class="eurl" data-at="1.6"><span>{REPO}</span></div></div>')


